def main() -> None:
    candidates: dict[str, dict] = {}
    for book in ("QBT", "ZHY"):
        data = json.loads((NORM / book / "rules.json").read_text(encoding="utf-8"))
        for r in data["rules"]:
            candidates[r["id"]] = r

    # 校验 curation 引用完整性
    missing = [cid for cell in CURATION.values() for entry in cell.values() for cid in entry["r"]
               if cid not in candidates]
    if missing:
        raise SystemExit(f"curation 引用了不存在的候选: {missing}")

    rules = []
    conflicts: list[dict] = []
    for dm, cells in CURATION.items():
        for month, entry in cells.items():
            for cid in entry["r"]:
                cand = candidates[cid]
                rule_id = f"TH-{cid}-{month}"  # 格限定 ID：多格引用同一候选不冲突
                effects = []
                for i, stem in enumerate(entry.get("p", [])):
                    effects.append({
                        "kind": "needStem", "targetStem": stem,
                        "element": ELEM_OF[stem],
                        "priority": "primary" if i == 0 else "secondary",
                    })
                for i, stem in enumerate(entry.get("s", [])):
                    effects.append({
                        "kind": "needStem", "targetStem": stem,
                        "element": ELEM_OF[stem], "priority": "secondary",
                    })
                for stem in entry.get("t", []):
                    effects.append({
                        "kind": "needStem", "targetStem": stem,
                        "element": ELEM_OF[stem], "priority": "tertiary",
                    })
                if entry.get("x"):
                    effects.append({"kind": "avoidStem", "targetStem": "癸", "element": "水",
                                    "priority": None,
                                    "conditionNote": "；".join(x["field"] + " " + x["operator"] + " " + json.dumps(x["value"], ensure_ascii=False) for x in entry["x"])})
                conditions = [
                    {"field": "dayMaster", "operator": "eq", "value": dm},
                    {"field": "monthBranch", "operator": "eq", "value": month},
                ] + entry.get("c", [])
                quote = (cand["originalQuotes"] or [""])[0]
                rules.append({
                    "id": rule_id,
                    "candidateId": cand["id"],
                    "domain": "tiaohou",
                    "conditions": conditions,
                    "effects": effects,
                    "exceptions": entry.get("x", []),
                    "modifiers": [],
                    "normalizationNotes": entry.get("n"),
                    "conflictNote": entry.get("conf"),
                    "source": cand["source"],
                    "provenance": [
                        {"level": "PROJECT_REFERENCE", "project": "徐乐吾八字知识库（用户提供 zip）",
                         "concept": f"穷通宝鉴评注逐月调候规则 {cand['id']}"},
                        {"level": "CLASSICAL_EXPLICIT" if cand["originalQuotes"] else "UNVERIFIED",
                         "project": None,
                         "concept": "古籍原文引文（穷通宝鉴原书口诀，经评注本页码定位）",
                         "note": (quote[:60] + "…") if len(quote) > 60 else quote},
                        {"level": "TIANZE_NORMALIZATION",
                         "project": "Tianze",
                         "concept": "目标干提取/优先级/条件结构化为 AI 整理层（M6 curation，非人工核验）",
                         "note": entry.get("n")},
                    ],
                    "quality": cand["quality"],
                    "status": "active",
                    "verification": {
                        "status": "MACHINE_CURATED",
                        "verifiedBy": "tianze-pipeline:build_tiaohou_rules.py",
                        "verifiedAt": None,
                        "method": "ai_curation",
                        "sourceChecked": True,
                        "notes": "M6 curation 由 AI 依候选原文完成（非人工）；升级 SOURCE_ALIGNED/HUMAN_VERIFIED 需真人对照扫描件",
                    },
                    "accuracyMatrix": {
                        "traceability": "PASS",
                        "textAccuracy": "OCR_RISK" if cand.get("ocrRisk") else "UNVERIFIED",
                        "interpretationAccuracy": "MACHINE_CURATED",
                        "engineAccuracy": "TESTED",
                    },
                })
                if entry.get("conf"):
                    conflicts.append({
                        "ruleIds": list(entry["r"]),
                        "conditionOverlap": {"dayMaster": dm, "monthBranch": month},
                        "description": entry["conf"],
                        "resolution": "specific-over-general",
                    })

    OUT.mkdir(parents=True, exist_ok=True)
    payload = {"domain": "tiaohou", "schemaVersion": "1.1.0", "count": len(rules), "rules": rules}
    (OUT / "rules.json").write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    conflict_records = [
        {**c, "kind": "SCHOOL_DIFFERENCE" if "两说" in c["description"] else "CONDITION_OVERLAP"}
        for c in conflicts
    ]
    (OUT / "conflicts.json").write_text(json.dumps({
        "schemaVersion": "1.1.0", "count": len(conflict_records), "conflicts": conflict_records,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    cells = {(r["conditions"][0]["value"], r["conditions"][1]["value"]) for r in rules}
    print(f"executable rules: {len(rules)} | cells covered: {len(cells)}/120 | conflicts: {len(conflicts)}")


if __name__ == "__main__":
    main()
